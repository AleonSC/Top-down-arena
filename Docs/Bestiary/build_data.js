#!/usr/bin/env node
// Builds the game's in-game Bestiary data (Assets/Scripts/Core/BestiaryData.cs) from this page's enemy table
// (the `B` shot kinds and `E` entries in arena-bestiary.html), so the pause menu's Field guide and the published
// page say the same things. Run it after editing an entry:   node Docs/Bestiary/build_data.js
// The live stats (health, speed, size, XP) aren't copied: the game reads them from Defs.cs.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "../..");
const html = fs.readFileSync(path.join(__dirname, "arena-bestiary.html"), "utf8");
const start = html.indexOf("const B = {"), end = html.indexOf("const BY = ");
if (start < 0 || end < 0) throw new Error("Couldn't find the B and E tables in arena-bestiary.html");
const rgb = (r, g, b) => [r, g, b];
const { B, E } = new Function("rgb", html.slice(start, end) + "\nreturn { B, E };")(rgb);

// Page ids that aren't EnemyType names.
const TYPE = { Warden: "Boss", Twins: "TwinA" };

const enumSrc = fs.readFileSync(path.join(root, "Assets/Scripts/Core/Defs.cs"), "utf8");
const enumBody = enumSrc.slice(enumSrc.indexOf("enum EnemyType"), enumSrc.indexOf("}", enumSrc.indexOf("enum EnemyType")));
const types = new Set(enumBody.replace(/\/\/.*$/gm, "").match(/\b[A-Z]\w*\b/g));

// The page talks about its own preview in places; the game has none, so those bits go.
const forGame = s => s
  .replace(/\s*\([^()]*\bpreview\b[^()]*\)/g, "")
  .replace(/ \(as here\)/g, "")
  .replace(/^Nothing shoots it here, so its healing \(Hungry, the Maw\) only shows: (\w)/, (m, c) => c.toUpperCase())
  .replace(/^Only one dummy here: in co-op/, "In co-op");
const pageOnly = [];
const str = s => {
  if (s == null) return "null";
  const t = forGame(String(s));
  if (/\bpreview\b|\bhere\b|\bdummy\b/i.test(t)) pageOnly.push(t);
  return JSON.stringify(t);  // JSON strings are valid C# literals here
};
const num = v => (Math.round(v * 1000) / 1000).toString() + "f";
const color = c => `new Rgba(${num(c[0])}, ${num(c[1])}, ${num(c[2])})`;
const labelled = (v, label) => typeof v === "function" ? label || "varies" : v;

function attack(a) {
  const k = a.kind ? B[a.kind] : null;
  if (a.kind && !k) throw new Error("Unknown shot kind " + a.kind + " in " + a.name);
  const dmg = a.dmg !== undefined ? labelled(a.dmg, a.dmgLabel) : k ? `${k.dmg} each` : null;
  const n = a.n !== undefined && a.n !== null ? labelled(a.n, a.nLabel) : null;
  const f = [
    `Name = ${str(a.name)}`,
    `Pattern = ${str(a.pattern)}`,
  ];
  if (k) f.push(`Shot = ${str(k.name)}`, `ShotColor = ${color(k.col)}`);
  if (n !== null) f.push(`Count = ${str(n)}`);
  if (a.speed !== undefined) f.push(`Speed = ${str(labelled(a.speed) + " px/s")}`);
  if (dmg !== null) f.push(`Damage = ${str(dmg)}`);
  if (typeof a.every === "number") f.push(`Every = ${num(a.every)}`);
  else if (a.every) f.push(`EveryText = ${str(a.every)}`);
  if (a.unscaled) f.push("Fixed = true");
  if (a.notes) f.push(`Notes = ${str(a.notes)}`);
  return `new BestiaryAttack { ${f.join(", ")} }`;
}

const out = [];
for (const e of E) {
  const type = TYPE[e.id] || e.id;
  if (!types.has(type)) throw new Error(`Bestiary entry ${e.id}: no EnemyType.${type} (add it to TYPE in build_data.js)`);
  const f = [
    `Type = EnemyType.${type}`,
    `Name = ${str(e.label || e.id)}`,
    `Group = ${str(e.cat)}`,
    `Wave = ${e.wave}`,
    `Appears = ${str(e.appears)}`,
    `Lead = ${str(e.lead)}`,
  ];
  if (e.locks) f.push(`Stages = new[] { ${e.locks.filter(l => l !== "Cycle").map(str).join(", ")} }`);
  f.push(`Attacks = new[]\n            {\n${(e.attacks || []).map(a => "                " + attack(a) + ",").join("\n")}\n            }`);
  if (e.notes && e.notes.length) f.push(`Notes = new[]\n            {\n${e.notes.map(n => "                " + str(n) + ",").join("\n")}\n            }`);
  out.push(`            new BestiaryEntry\n            {\n${f.map(x => "                " + x.replace(/\n {12}/g, "\n                ") + ",").join("\n")}\n            },`);
}

const cs = `// Generated by Docs/Bestiary/build_data.js from Docs/Bestiary/arena-bestiary.html. Don't edit by hand: edit the
// page's entry and run  node Docs/Bestiary/build_data.js  again.
namespace Arena
{
    public static partial class BestiaryData
    {
        static readonly BestiaryEntry[] FromPage =
        {
${out.join("\n")}
        };
    }
}
`;
const dest = path.join(root, "Assets/Scripts/Core/BestiaryData.Generated.cs");
fs.writeFileSync(dest, cs);
console.log(path.relative(root, dest) + ": " + E.length + " entries");
for (const t of pageOnly)
  console.log("Check this reads right in the game (it may talk about the page): " + t.slice(0, 160));
