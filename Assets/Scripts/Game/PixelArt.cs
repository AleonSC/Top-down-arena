        static readonly Dictionary<string, Texture2D> cache = new Dictionary<string, Texture2D>();

        /// The icon for an upgrade, or null if it has none.
        public static Texture2D ForUpgrade(string upgradeName)
        {
            string key;
            return ByUpgrade.TryGetValue(upgradeName, out key) ? Get(key) : null;
        }

        public static Texture2D Get(string key)
        {
            Texture2D tex;
            if (cache.TryGetValue(key, out tex))
                return tex;
            string[] rows;
            if (!Icons.TryGetValue(key, out rows))
                return null;
            tex = new Texture2D(Size, Size, TextureFormat.RGBA32, false)
            {
                filterMode = FilterMode.Point,
                wrapMode = TextureWrapMode.Clamp,
                hideFlags = HideFlags.HideAndDontSave,
            };
            var px = new Color32[Size * Size];
            for (int y = 0; y < Size; y++)
                for (int x = 0; x < Size; x++)
                {
                    Color32 c;
                    // Textures start at the bottom row, the art at the top.
                    px[(Size - 1 - y) * Size + x] = Palette.TryGetValue(rows[y][x], out c) ? c : new Color32(0, 0, 0, 0);
                }
            tex.SetPixels32(px);
            tex.Apply();
            cache[key] = tex;
            return tex;
        }
