using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Arena;

// Turns the designed wave sets in Data/Waves/*.waves (saved by the F1 wave editor) into C# that builds them, in
// Assets/Scripts/Core/DesignedWaves.Generated.cs, so a final build carries them with no loose files. It reads each
// file with the game's own parser (WaveSet.Parse), so it can't disagree with the game, and stops on any problem.
// Run it with Tools/WaveGen/build.sh after adding or changing a .waves file.
static class Gen
{
    static string F(float v) => v.ToString("R", CultureInfo.InvariantCulture) + "f";

    static string Str(string s) => s == null ? "null" : "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    static int Main(string[] args)
    {
        string root = args.Length > 0 ? args[0] : ".";
        string src = Path.Combine(root, "Data", "Waves");
        string outPath = Path.Combine(root, "Assets", "Scripts", "Core", "DesignedWaves.Generated.cs");
        var files = Directory.Exists(src) ? Directory.GetFiles(src, "*.waves").OrderBy(f => Path.GetFileName(f), StringComparer.Ordinal).ToArray() : new string[0];
        var names = new List<string>();
        var sets = new StringBuilder();
        bool failed = false;
        for (int k = 0; k < files.Length; k++)
        {
            string name = Path.GetFileNameWithoutExtension(files[k]);
            List<string> problems;
            var set = WaveSet.Parse(File.ReadAllText(files[k]), out problems);
            if (problems.Count > 0)
            {
                failed = true;
                foreach (var p in problems)
                    Console.Error.WriteLine("Data/Waves/" + name + ".waves: " + p);
                continue;
            }
            if (names.Contains(name, StringComparer.OrdinalIgnoreCase))
            {
                failed = true;
                Console.Error.WriteLine("Data/Waves/" + name + ".waves: another file has the same name");
                continue;
            }
            names.Add(name);
            sets.Append("\n        static WaveSet Set").Append(names.Count - 1).Append("()  // ").Append(name).Append(".waves\n        {\n");
            sets.Append("            var s = new WaveSet { Name = ").Append(Str(set.Name)).Append(", Loop = ").Append(set.Loop ? "true" : "false").Append(" };\n");
            for (int i = 0; i < set.Points.Length; i++)
                sets.Append("            s.Points[").Append(i).Append("] = new V2(").Append(F(set.Points[i].X)).Append(", ").Append(F(set.Points[i].Y)).Append(");\n");
            sets.Append("            DesignWave w;\n            DesignGroup g;\n");
            foreach (var w in set.Waves)
            {
                sets.Append("            w = new DesignWave { Level = ").Append(w.Level).Append(" };\n            s.Waves.Add(w);\n");
                foreach (var g in w.Groups)
                {
                    sets.Append("            g = new DesignGroup { Name = ").Append(Str(g.Name)).Append(", Squad = ").Append(Str(g.Squad)).Append(", From = ").Append(Str(g.From))
                        .Append(", At = ").Append(F(g.At)).Append(", Every = ").Append(F(g.Every)).Append(", Arrive = ArriveMode.").Append(g.Arrive).Append(" };\n");
                    if (g.Members.Count > 0)
                        sets.Append("            g.Members.AddRange(new[] { ").Append(string.Join(", ", g.Members.Select(m => "EnemyType." + m))).Append(" });\n");
                    sets.Append("            w.Groups.Add(g);\n");
                }
                foreach (var p in w.Props)
                    sets.Append("            w.Props.Add(new DesignProp { Kind = PropKind.").Append(p.Kind).Append(", Pos = new V2(").Append(F(p.Pos.X)).Append(", ").Append(F(p.Pos.Y)).Append(") });\n");
            }
            sets.Append("            return s;\n        }\n");
        }
        if (failed)
        {
            Console.Error.WriteLine("Nothing written: fix the files above (open them in the F1 wave editor, or edit the text) and run it again.");
            return 1;
        }
        var o = new StringBuilder();
        o.Append("// <auto-generated>\n// Built by Tools/WaveGen/build.sh from Data/Waves/*.waves (the F1 wave editor's files). Don't edit it by hand:\n");
        o.Append("// change the .waves files and run the script again.\n// </auto-generated>\n");
        o.Append("namespace Arena\n{\n    public static partial class DesignedWaves\n    {\n");
        o.Append("        /// Every designed wave set built into the game, by its file name (Data/Waves/<name>.waves).\n");
        o.Append("        public static readonly string[] Names = { ").Append(string.Join(", ", names.Select(Str))).Append(" };\n\n");
        o.Append("        static WaveSet Build(string name)\n        {\n            switch (name)\n            {\n");
        for (int i = 0; i < names.Count; i++)
            o.Append("                case ").Append(Str(names[i])).Append(": return Set").Append(i).Append("();\n");
        o.Append("                default: return null;\n            }\n        }\n");
        o.Append(sets);
        o.Append("    }\n}\n");
        string text = o.ToString();
        bool same = File.Exists(outPath) && File.ReadAllText(outPath) == text;
        if (!same)
            File.WriteAllText(outPath, text);
        Console.WriteLine("Assets/Scripts/Core/DesignedWaves.Generated.cs: " + names.Count + " wave set" + (names.Count == 1 ? "" : "s") + " (" + string.Join(", ", names) + ")" + (same ? ", unchanged" : ""));
        return 0;
    }
}
